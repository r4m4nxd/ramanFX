// Bundles the app's own journal maths (src/core: enrich, riskStatus, rule score, plans) into ONE dependency-free ES
// module for the trader-coach edge function, so the coach runs exactly the app's logic instead of a re-implementation.
// Run after changing any of those src/core files: node scripts/build-coach-core.mjs
// (src/core/traderCoach.test.ts fails while the committed bundle is out of date.)
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(root, 'supabase/functions/trader-coach/app-core.js');
export const ENTRY = `
export { enrich, computeStats, groupStats, normTag, balanceSeries } from '@/core/stats';
export { riskStatus } from '@/core/risk';
export { scoreRules, autoMarks, resolveMarks, fmtR, RULES } from '@/core/ruleScore';
export { matchPlan, blankPlan } from '@/core/strategy';
export { specFor } from '@/core/instruments';
export { dayKey, parseTs } from '@/core/time';
`;
const HEADER = '// GENERATED by scripts/build-coach-core.mjs from src/core (the app\'s own code). Do not edit by hand.\n// deno-lint-ignore-file\n';

export async function bundle() {
  const r = await build({
    stdin: { contents: ENTRY, resolveDir: root, sourcefile: 'coach-core-entry.ts', loader: 'ts' },
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2021', write: false, legalComments: 'none',
    alias: { '@': path.join(root, 'src') }, logLevel: 'silent',
  });
  return HEADER + r.outputFiles[0].text.replaceAll(root, '.');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  writeFileSync(OUT, await bundle());
  console.log(`wrote ${path.relative(root, OUT)}`);
}
